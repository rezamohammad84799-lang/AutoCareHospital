/*CREATING A VIEW FROM THE CLEANDATA*/
CREATE OR ALTER VIEW vw_AdmissionData AS
/* CREATING A CTE TO EXTRCAT NON-DUBLICATES DATA*/
WITH CleanData AS(
/* FINDIND POTENTIAL DUPLICATES RECORDS BY USING WINDOWS FUNCTIONS*/
SELECT *, 
ROW_NUMBER() OVER(PARTITION BY MRD_No, D_O_A, D_O_D ORDER BY MRD_No) AS DUP_No
FROM [HDHI Admission data]
--ORDER BY MRD_No
)
/* SELECT NON-DUOLICATE DATA*/
SELECT * 
FROM CleanData
WHERE DUP_No = 1 AND MRD_No IS NOT NULL
--ORDER BY MRD_No

