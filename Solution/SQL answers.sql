/*HERE OUR PRIMARY FOCUS IS ANALYZING THE DISCHARGE DOMAIN*/
/* Q1 TOTAL DISCHARGES*/
SELECT COUNT(*) AS TOTAL_DISCHARGES
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE'

/*Q2 AVG DAILY DISCHARGE RATE*/
/*IS THE TOTAL DISCHARGES DIVIDED BY TOTAL LENGTH OF STAY*/
SELECT
(SELECT COUNT(*) AS TOTAL_DISCHARGES
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE')/ (SELECT SUM(DURATION_OF_STAY) AS TOTAL_LENGTH_OF_STAY
FROM vw_AdmissionData)
-- CASTING THIS
SELECT
    CAST(
CAST((SELECT COUNT(*) AS TOTAL_DISCHARGES
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE') AS float)/ CAST((SELECT SUM(DURATION_OF_STAY) AS TOTAL_LENGTH_OF_STAY
FROM vw_AdmissionData) AS float) AS decimal(10, 2)) *100 AS AVG_DAILY_DISCHARGE_RATE
/*SOLVING THE SAME QUESTION BY AVOIDING SUBSQUERY*/
SELECT 
     ROUND(SUM(CASE WHEN OUTCOME = 'DISCHARGE' THEN 1.0 ELSE 0.0 END) /
     SUM(DURATION_OF_STAY), 2) *100 AS AVG_DAILY_DISCHARGE_RATE
     FROM vw_AdmissionData
/*Q3 AVERAGE LENGTH OF STAY*/
-- IT IS THE TOTAL LENGTH OF STAY DIVIDED BY TOTAL DISCHARGES--
SELECT 
    CAST(ROUND(SUM(DURATION_OF_STAY)/  
    SUM(CASE WHEN OUTCOME = 'DISCHARGE' THEN 1.0 ELSE 0.0 END), 0) AS INT) AS AVG_LENGTH_OF_STAY 
FROM vw_AdmissionData

/*Q4 DISTRIBUTION OF DISCHARGES BY EACH GROUP*/
-- <16 PEDIATRICS
-- 16<65 ADULTS
-- >=65 SENIOR CITIZENS
SELECT
     CASE WHEN AGE < 16 THEN 'PAEDIATRICS'
          WHEN AGE < 65 THEN 'ADULTS'
          WHEN AGE >= 65 THEN 'SENIOR CITIZEN'
          ELSE 'UNKNOWN'
    END AS AGE_GROUP, COUNT(*) AS AGE_DISTRIBUTION
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE'
GROUP BY 
     CASE WHEN AGE < 16 THEN 'PAEDIATRICS'
          WHEN AGE < 65 THEN 'ADULTS'
          WHEN AGE >= 65 THEN 'SENIOR CITIZENS'
          ELSE 'UNKNOWN'
    END
ORDER BY MAX(AGE);

/*Q5 DISTRIBUTION OF DISCHARGES BY GENDER*/
SELECT GENDER, COUNT(GENDER) AS GENDER_DISTRIBUTION
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE'
GROUP BY GENDER
ORDER BY 2 DESC

/*Q6 DISTRIBUTION OF DISCHARGE BY DAY OF THE WEEK*/
SELECT DATEPART(WEEKDAY, D_O_D) AS DAY_OF_WEEK, COUNT(*) AS DAY_DISTRIBUTION
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE'
GROUP BY DATEPART(WEEKDAY, D_O_D)
ORDER BY 2 DESC
-- GETTING THE DATE NAME
SELECT FORMAT(D_O_D, 'dddd') AS DAY_OF_WEEK, COUNT(*) AS DAY_DISTRIBUTION
FROM vw_AdmissionData
WHERE OUTCOME = 'DISCHARGE' AND D_O_D IS NOT NULL
GROUP BY FORMAT(D_O_D, 'dddd')
ORDER BY 2 DESC

/* Let's solve some real-life business questions*/
/* How many hospital admissions occur each month?*/

SELECT month_year,
COUNT(*) AS TOTAL_ADMISSION
FROM vw_AdmissionData
WHERE month_year IS NOT NULL 
GROUP BY month_year
ORDER BY TRY_CONVERT(DATE, '01-' +  [month_year])

/*Hospital mortality rate by admission type*/
/*Does emergency admission have a higher expiry rate than OPD admission?*/

SELECT [TYPE_OF_ADMISSION_EMERGENCY_OPD] AS ADMISSION_TYPE,
COUNT(*) AS TOTAL_ADMISSION,
SUM(CASE WHEN UPPER(TRIM(OUTCOME)) = 'EXPIRY'
THEN 1 ELSE 0 END) AS TOTAL_EXPIRY,
CAST(
SUM(CASE WHEN UPPER(TRIM(OUTCOME)) = 'EXPIRY'
THEN 1 ELSE 0 END) *100.0/ COUNT(*) AS DECIMAL(10,2) ) AS EXPIRY_RATE_PERCENTAGE
FROM vw_AdmissionData
WHERE  [TYPE_OF_ADMISSION_EMERGENCY_OPD] IN ('E' , 'O')
GROUP BY  [TYPE_OF_ADMISSION_EMERGENCY_OPD];

/* Which admission type has a higher average hospital stay */

SELECT [TYPE_OF_ADMISSION_EMERGENCY_OPD] AS ADMISSION_TYPE,
COUNT(*) AS TOTAL_VALID_ADMISSION,
AVG(CAST([DURATION_OF_STAY] AS decimal(10, 2)) ) AS AVG_LENGTH_OF_STAY,
MIN([DURATION_OF_STAY]) AS MIN_STAY,
MAX([DURATION_OF_STAY]) AS MAX_STAY
FROM vw_AdmissionData 
WHERE [TYPE_OF_ADMISSION_EMERGENCY_OPD] IN ('E', 'O')
AND [DURATION_OF_STAY] > 0
GROUP BY [TYPE_OF_ADMISSION_EMERGENCY_OPD];

/*Additional validation queries
Before trusting the results.
Check 1: Duplicate admission identifiers*/
SELECT SNO, COUNT(*) AS RECORD
FROM vw_AdmissionData
GROUP BY SNO
HAVING COUNT(*) > 1;

/*Invalid length of stay*/
